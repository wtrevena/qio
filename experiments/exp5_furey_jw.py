"""Experiment 5: the Jordan-Wigner bridge between Furey's Cl(6) and 3 qubits.

Observation: Furey's construction lives in Cl(6), generated by 3 fermionic
ladder operators (alpha_i, alpha_i^dagger) built from complex octonions;
Cl(6) =~ M_8(C) = the full operator algebra of THREE QUBITS, and the
Jordan-Wigner transformation provides a canonical isomorphism. Under it,
Furey's minimal-left-ideal basis states (one generation of fermions) become
the 3-qubit computational basis, graded by Hamming weight = 3 x electric
charge (for the ideal containing nu, d-bar, u, e+).

This script constructs the map explicitly, verifies the CAR algebra, and
computes the entanglement structure of physically natural states.
"""
import json
import numpy as np
import qio_lib as q

I2 = np.eye(2); X = np.array([[0, 1], [1, 0]], complex)
Y = np.array([[0, -1j], [1j, 0]]); Z = np.diag([1., -1.]).astype(complex)
sm = np.array([[0, 1], [0, 0]], complex)   # |1><0|? no: sm|1>=|0|... annihilator on {|0>,|1>}
def kron3(a, b, c):
    return np.kron(np.kron(a, b), c)

# Jordan-Wigner: f_1 = sm x I x I, f_2 = Z x sm x I, f_3 = Z x Z x sm
F = [kron3(sm, I2, I2), kron3(Z, sm, I2), kron3(Z, Z, sm)]
# verify CAR: {f_i, f_j^+} = delta_ij, {f_i, f_j} = 0
for i in range(3):
    for j in range(3):
        acomm = F[i] @ F[j].conj().T + F[j].conj().T @ F[i]
        assert np.allclose(acomm, np.eye(8) * (i == j))
        assert np.allclose(F[i] @ F[j] + F[j] @ F[i], 0)
print("CAR verified: Cl(6) =~ M_8(C) realized on 3 qubits via Jordan-Wigner")

out = {'verified_CAR': True}

# number operator and charge: Q = N/3 on the (nu, d-bar, u, e+) ideal
N = sum(f.conj().T @ f for f in F)
basis_labels = {0: 'nu (weight 0, Q=0)',
                1: 'dbar_b (W1, Q=1/3)', 2: 'dbar_g (W1, Q=1/3)', 4: 'dbar_r (W1, Q=1/3)',
                3: 'u_r (W2, Q=2/3)', 5: 'u_g (W2, Q=2/3)', 6: 'u_b (W2, Q=2/3)',
                7: 'e+ (weight 3, Q=1)'}
out['charge_spectrum'] = {lbl: float(np.real(N[i, i])) / 3
                          for i, lbl in basis_labels.items()}

def report(name, vec, note=""):
    v = np.asarray(vec, complex).reshape(1, 8)
    v = v / np.linalg.norm(v)
    S = q.single_qubit_entropies(v)[0]
    tau = float(q.three_tangle(v)[0])
    out['states'][name] = dict(S=[float(s) for s in S], tau3=tau, note=note)
    print(f"{name:42s} S={S.round(4)} tau3={tau:.4f}")

out['states'] = {}
e = np.eye(8)
# individual particle states: separable by construction
report("particle basis state (any)", e[1], "Fock basis = computational basis: S=(0,0,0); "
       "single particles carry NO entanglement in this frame")
# color-symmetric quark combinations
report("color-uniform dbar (W state)", (e[1] + e[2] + e[4]) / np.sqrt(3),
       "SU(3)-flavor-symmetric weight-1 combo = the W state, tau3=0")
report("color-uniform u (W-bar state)", (e[3] + e[5] + e[6]) / np.sqrt(3),
       "weight-2 uniform combo = flipped W state")
# charge-superselection-violating superposition
report("nu + e+ (GHZ)", (e[0] + e[7]) / np.sqrt(2),
       "GHZ = maximal violation of charge superselection (Delta Q = 1)")
report("nu + color-uniform dbar", (np.sqrt(3) * e[0] + e[1] + e[2] + e[4]) / np.sqrt(6),
       "lepton-quark superposition (Delta Q = 1/3)")

# ---- gauge action vs tensor factorization ----
# Color SU(3) acts on the modes: f_i -> U_ij f_j. Implement the induced
# unitary on the 8-dim Fock space for a sample U (discrete Fourier matrix)
# and ask: is entanglement invariant? (i.e., is the induced map a LOCAL
# unitary on the qubit factorization?)
w3 = np.exp(2j * np.pi / 3)
U = np.array([[1, 1, 1], [1, w3, w3**2], [1, w3**2, w3**4]]) / np.sqrt(3)
# induced Bogoliubov (number-conserving) unitary: Gamma = exp(i K), easier:
# build directly on Fock basis by mapping weight-1 sector with U, weight-2
# with the induced action on antisymmetric pairs (= conj(U) * det factor),
# weights 0,3 invariant.
G = np.zeros((8, 8), complex)
G[0, 0] = 1; G[7, 7] = 1
w1_idx = [4, 2, 1]   # f1+|0>=|100>=4, f2+|0>=|010>=2, f3+|0>=|001>=1
for a in range(3):
    for b in range(3):
        G[w1_idx[a], w1_idx[b]] = U[a, b]
# weight-2 states: f_i+ f_j+ |0>, ordered pairs (1,2),(1,3),(2,3) -> indices
w2_pairs = [(0, 1), (0, 2), (1, 2)]
w2_idx = [6, 5, 3]   # |110>, |101>, |011>
for A, (i, j) in enumerate(w2_pairs):
    for Bp, (k, l) in enumerate(w2_pairs):
        G[w2_idx[A], w2_idx[Bp]] = U[i, k] * U[j, l] - U[i, l] * U[j, k]
assert np.allclose(G @ G.conj().T, np.eye(8)), "induced action must be unitary"

# does G preserve single-qubit entropies of basis states?
v = e[4].reshape(1, 8)  # dbar_r
Gv = (G @ e[4]).reshape(1, 8)
S_before = q.single_qubit_entropies(v)[0]
S_after = q.single_qubit_entropies(Gv)[0]
out['gauge_vs_entanglement'] = dict(
    S_before=[float(s) for s in S_before], S_after=[float(s) for s in S_after],
    is_local_unitary=bool(np.allclose(S_before, S_after, atol=1e-10)),
    note="A color rotation (DFT in color space) maps a separable quark state "
         "to an entangled one: gauge transformations are NOT local unitaries "
         "of the qubit factorization. Entanglement in the JW frame is "
         "gauge-frame dependent; only gauge-invariant combinations of "
         "invariants can be physical.")
print(f"color DFT on dbar_r: S {S_before.round(4)} -> {S_after.round(4)} "
      f"(local unitary: {np.allclose(S_before, S_after)})")

with open('results/exp5_results.json', 'w') as f:
    json.dump(out, f, indent=2)
print("Saved results/exp5_results.json")
